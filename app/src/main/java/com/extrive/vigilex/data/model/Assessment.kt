package com.extrive.vigilex.data.model

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonObject

/*
 * Saved assessments as the backend returns them (backend/app/schemas/analysis.py).
 * Field names mirror the backend exactly. Scores and risk labels are the
 * values the CV pipeline produced; the app never recomputes them.
 */

/** One method's stored result: RULA (scale 7) or REBA (scale 15). */
@Serializable
data class MethodResultDto(
    val score: Int? = null,
    @SerialName("scale_max") val scaleMax: Int,
    val risk: String? = null,
    @SerialName("frames_scored") val framesScored: Int = 0,
    @SerialName("risk_distribution") val riskDistribution: Map<String, Int> = emptyMap()
)

/** Measured evidence behind an intervention. */
@Serializable
data class InterventionEvidenceDto(
    @SerialName("average_deg") val averageDeg: Double? = null,
    @SerialName("peak_deg") val peakDeg: Double? = null,
    @SerialName("frames_flagged") val framesFlagged: Int = 0,
    @SerialName("frames_measured") val framesMeasured: Int = 0
)

/**
 * A workplace posture recommendation generated by the backend intervention
 * engine (backend/app/services/interventions.py) from measured posture.
 * `area`: back, knees, neck, upper_arm. `priority`: high, medium.
 * `status`: attention, elevated, high. Wording comes from the backend as is.
 */
@Serializable
data class InterventionDto(
    val area: String,
    val priority: String,
    val status: String,
    val title: String,
    val observation: String,
    val recommendation: String,
    val evidence: InterventionEvidenceDto? = null
)

/** The back/trunk posture metric: trunk inclination from upright, with lean direction and view reliability. */
@Serializable
data class BackPostureDto(
    @SerialName("average_deg") val averageDeg: Double? = null,
    @SerialName("peak_deg") val peakDeg: Double? = null,
    @SerialName("frames_measured") val framesMeasured: Int = 0,
    @SerialName("frames_inclined") val framesInclined: Int = 0,
    val direction: String? = null,
    @SerialName("side_on_fraction") val sideOnFraction: Double = 0.0,
    @SerialName("view_limited") val viewLimited: Boolean = false
)

/**
 * An Extrive product suggested for evaluation because of a specific finding
 * (backend/app/services/products.py). Product text is the approved content the
 * backend serves; `contentStatus` is "incomplete" when it is missing.
 */
@Serializable
data class ProductRecommendationDto(
    @SerialName("product_id") val productId: String,
    val name: String,
    val maker: String,
    val category: String? = null,
    @SerialName("linked_area") val linkedArea: String,
    /** "primary" when the linked finding is the priority action. */
    val role: String,
    val headline: String,
    val rationale: String,
    @SerialName("intended_use") val intendedUse: String? = null,
    @SerialName("operating_principle") val operatingPrinciple: String? = null,
    @SerialName("task_types") val taskTypes: List<String> = emptyList(),
    val suitability: List<String> = emptyList(),
    @SerialName("complementary_actions") val complementaryActions: List<String> = emptyList(),
    @SerialName("evidence_note") val evidenceNote: String? = null,
    val qualification: String,
    val sources: List<String> = emptyList(),
    @SerialName("content_status") val contentStatus: String,
    @SerialName("content_gaps") val contentGaps: List<String> = emptyList()
) {
    val verified: Boolean get() = contentStatus == "verified"
}

/** How far the camera view supports the 2D angle measurements. */
@Serializable
data class MeasurementReliabilityDto(
    /** "limited" or "no_limitation_detected" (not a confidence rating). */
    val status: String,
    @SerialName("side_on_fraction") val sideOnFraction: Double? = null,
    @SerialName("detection_fraction") val detectionFraction: Double? = null,
    val explanation: String,
    val title: String? = null,
    val reasons: List<String> = emptyList(),
    val recommendation: String? = null
) {
    val limited: Boolean get() = status == "limited"
}

@Serializable
data class ComponentRowDto(
    val name: String,
    val measured: Boolean,
    @SerialName("angle_deg") val angleDeg: Double? = null,
    val band: Int? = null,
    @SerialName("max_band") val maxBand: Int? = null
)

/** One method's components at the first frame where it reached its peak score. */
@Serializable
data class ComponentTableDto(
    val method: String,
    val title: String,
    val score: Int,
    @SerialName("scale_max") val scaleMax: Int,
    @SerialName("frame_number") val frameNumber: Int,
    @SerialName("frame_time_sec") val frameTimeSec: Double? = null,
    val rows: List<ComponentRowDto> = emptyList()
)

/** One history row: GET /api/v1/assessments items, overview `latest`. */
@Serializable
data class AssessmentSummaryDto(
    val id: String,
    val status: String,
    @SerialName("created_at") val createdAt: String,
    @SerialName("updated_at") val updatedAt: String? = null,
    @SerialName("video_name") val videoName: String? = null,
    @SerialName("duration_sec") val durationSec: Double? = null,
    val rula: MethodResultDto? = null,
    val reba: MethodResultDto? = null,
    @SerialName("overall_risk") val overallRisk: String? = null,
    @SerialName("methodology_version") val methodologyVersion: String? = null,
    @SerialName("derived_angles") val derivedAngles: DerivedAngles? = null,
    /** One plain-language sentence: overall posture risk and the main opportunities. */
    @SerialName("action_summary") val actionSummary: String? = null,
    /** Most important first: the first is the priority action. Empty when no region needs action. */
    val interventions: List<InterventionDto> = emptyList(),
    @SerialName("product_recommendations") val productRecommendations: List<ProductRecommendationDto> = emptyList(),
    @SerialName("measurement_reliability") val measurementReliability: MeasurementReliabilityDto? = null
)

/** GET /api/v1/assessments: newest first, completed only unless another status is asked for. */
@Serializable
data class AssessmentPageDto(
    val items: List<AssessmentSummaryDto>,
    val total: Int,
    val limit: Int,
    val offset: Int
)

/**
 * GET /api/v1/assessments/{id}. Only the fields the app reads are declared;
 * `analysis` is the stored result in the exact shape POST /analyze-video
 * returned, null unless the assessment completed.
 */
@Serializable
data class AssessmentDetailDto(
    val id: String,
    val status: String,
    val summary: AssessmentSummaryDto,
    val analysis: JsonObject? = null,
    @SerialName("report_available") val reportAvailable: Boolean = false
)

@Serializable
data class OverviewMethodStatsDto(
    @SerialName("assessments_scored") val assessmentsScored: Int,
    val average: Double? = null,
    val highest: Int? = null,
    @SerialName("scale_max") val scaleMax: Int,
    val distribution: Map<String, Int> = emptyMap()
)

@Serializable
data class ElevatedMeasurementDto(
    val metric: String,
    val label: String,
    @SerialName("assessments_measured") val assessmentsMeasured: Int,
    @SerialName("assessments_elevated") val assessmentsElevated: Int
)

/** GET /api/v1/overview: aggregates over completed assessments; zeros and empty lists when there are none. */
@Serializable
data class OverviewDto(
    @SerialName("total_assessments") val totalAssessments: Int,
    @SerialName("recent_window_days") val recentWindowDays: Int,
    @SerialName("recent_assessments") val recentAssessments: Int,
    @SerialName("overall_risk_distribution") val overallRiskDistribution: Map<String, Int> = emptyMap(),
    val rula: OverviewMethodStatsDto,
    val reba: OverviewMethodStatsDto,
    @SerialName("elevated_measurements") val elevatedMeasurements: List<ElevatedMeasurementDto> = emptyList(),
    val latest: List<AssessmentSummaryDto> = emptyList()
)

@Serializable
data class ReportFindingDto(
    val title: String,
    val detail: String,
    val status: String
)

@Serializable
data class RegionMeasurementDto(
    val metric: String,
    val label: String,
    @SerialName("average_deg") val averageDeg: Double? = null,
    @SerialName("maximum_deg") val maximumDeg: Double? = null,
    @SerialName("peak_severity") val peakSeverity: String? = null,
    @SerialName("frames_measured") val framesMeasured: Int = 0,
    @SerialName("frames_at_peak_severity") val framesAtPeakSeverity: Int = 0,
    @SerialName("frames_flagged") val framesFlagged: Int = 0
)

/** What the server-generated PDF contains, built only from the stored assessment. */
@Serializable
data class ReportContentDto(
    @SerialName("assessment_id") val assessmentId: String,
    val title: String,
    @SerialName("video_name") val videoName: String? = null,
    @SerialName("analyzed_at") val analyzedAt: String,
    @SerialName("duration_sec") val durationSec: Double? = null,
    @SerialName("overall_risk") val overallRisk: String? = null,
    val rula: MethodResultDto? = null,
    val reba: MethodResultDto? = null,
    val observation: String? = null,
    @SerialName("action_summary") val actionSummary: String? = null,
    val interventions: List<InterventionDto> = emptyList(),
    @SerialName("product_recommendations") val productRecommendations: List<ProductRecommendationDto> = emptyList(),
    @SerialName("measurement_reliability") val measurementReliability: MeasurementReliabilityDto? = null,
    @SerialName("back_posture") val backPosture: BackPostureDto? = null,
    val findings: List<ReportFindingDto> = emptyList(),
    val measurements: List<RegionMeasurementDto> = emptyList(),
    @SerialName("measurement_note") val measurementNote: String = "",
    @SerialName("evidence_frames") val evidenceFrames: Int = 0,
    /** Main sections in reading order, then the technical appendix. */
    val sections: List<String> = emptyList(),
    @SerialName("technical_section") val technicalSection: String = "",
    @SerialName("component_note") val componentNote: String = "",
    @SerialName("component_tables") val componentTables: List<ComponentTableDto> = emptyList(),
    val methodology: List<String> = emptyList(),
    val limitations: List<String> = emptyList(),
    @SerialName("methodology_version") val methodologyVersion: String? = null
)

/** POST and GET /api/v1/assessments/{id}/report. `download_url` is an API path, never a file path. */
@Serializable
data class ReportMetadataDto(
    @SerialName("assessment_id") val assessmentId: String,
    val status: String,
    @SerialName("generated_at") val generatedAt: String,
    @SerialName("file_name") val fileName: String,
    @SerialName("size_bytes") val sizeBytes: Long,
    @SerialName("download_url") val downloadUrl: String,
    val content: ReportContentDto
)
