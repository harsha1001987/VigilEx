package com.extrive.vigilex.ui.report

import android.content.Context
import android.graphics.pdf.PdfRenderer
import android.os.ParcelFileDescriptor
import com.extrive.vigilex.data.api.ApiResult
import com.extrive.vigilex.data.model.ReportMetadataDto
import com.extrive.vigilex.data.repository.AssessmentRepository
import com.extrive.vigilex.ui.components.PRODUCT_SECTION
import com.extrive.vigilex.ui.components.TECHNICAL_SECTION
import java.io.File
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * The report's sections in reading order, then the technical appendix.
 * Matches report_sections() in backend/app/services/reports.py; the product
 * section is present only when a finding qualifies for an Extrive product.
 */
fun reportSections(hasProduct: Boolean): List<String> = listOfNotNull(
    "Overall assessment",
    "Priority action",
    PRODUCT_SECTION.takeIf { hasProduct },
    "Other actions",
    "Measurements",
    "Posture evidence",
    "Camera view and reliability",
    TECHNICAL_SECTION
)

/** A server-generated report, downloaded to this device for preview, export and sharing. */
data class GeneratedReport(val metadata: ReportMetadataDto, val file: File, val pageCount: Int)

sealed interface ReportOutcome {
    data class Ready(val report: GeneratedReport) : ReportOutcome

    /** [generated] tells whether the server created the report and only the download failed. */
    data class Failed(val generated: Boolean, val error: ApiResult.Error) : ReportOutcome
}

/**
 * Reports are generated by the VigilEx server from the stored assessment
 * (POST /assessments/{id}/report), so the PDF holds exactly the saved scores.
 * This downloads it into the cache directory FileProvider shares from.
 */
class ReportService(
    private val context: Context,
    private val repository: AssessmentRepository = AssessmentRepository()
) {
    private val directory: File get() = File(context.cacheDir, REPORT_DIR)

    /** Generates (or regenerates) the report on the server, then downloads it. */
    suspend fun generate(assessmentId: String): ReportOutcome =
        when (val created = repository.generateReport(assessmentId)) {
            is ApiResult.Error -> ReportOutcome.Failed(generated = false, error = created)
            is ApiResult.Success -> download(created.data)
        }

    /** The report already generated for this assessment, or null when there is none (or it can't be fetched). */
    suspend fun existing(assessmentId: String): GeneratedReport? =
        when (val found = repository.report(assessmentId)) {
            is ApiResult.Error -> null
            is ApiResult.Success -> (download(found.data) as? ReportOutcome.Ready)?.report
        }

    private suspend fun download(metadata: ReportMetadataDto): ReportOutcome =
        when (val file = repository.downloadReport(metadata, directory)) {
            is ApiResult.Error -> ReportOutcome.Failed(generated = true, error = file)
            is ApiResult.Success -> ReportOutcome.Ready(
                GeneratedReport(metadata, file.data.file, pageCount(file.data.file))
            )
        }

    private suspend fun pageCount(file: File): Int = withContext(Dispatchers.IO) {
        try {
            ParcelFileDescriptor.open(file, ParcelFileDescriptor.MODE_READ_ONLY).use { fd ->
                PdfRenderer(fd).use { it.pageCount }
            }
        } catch (e: Exception) {
            0 // The page count is informational; the PDF itself was verified on download.
        }
    }

    companion object {
        /** Matches res/xml/report_paths.xml. */
        const val REPORT_DIR = "reports"
    }
}
